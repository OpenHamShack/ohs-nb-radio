#!/usr/bin/env python3
"""Generate a user guide's settings reference from the Settings dialog itself.

    tools/settings-ref.py [--app nb|ham]            # print the reference (Markdown)
    tools/settings-ref.py [--app nb|ham] --write    # replace it in the app's guide
    tools/settings-ref.py [--app nb|ham] --check    # exit 1 if the guide is out of date

--app nb (the default) is QO-100 NB and docs/USERGUIDE.md; --app ham is
OpenHamShack Radio and docs/ham/USERGUIDE.md. The two apps share the dialog's
machinery (ohscore/ui/settings.py) but not its pages, labels or state
table, so each guide is generated from its own app's dialog.

The reference is built by opening the real Settings dialog offscreen and
reading back, page by page, which settings it shows, under what label, with
which help sentence - so the guide says exactly what the window says. Ranges,
defaults and units come from the engine's state table (ohsnb/state.py or
ohsradio/state.py, the single source of truth the dialog itself is built from).
Writing the table by hand was the alternative; it would be wrong the first
time a help sentence or a limit changed, and nothing would say so. --check
exists so a test or a release can say so.

Window-only preferences (theme, waterfall palette, second display, the
licence tick) are not engine settings and have no entry in the state table;
the guide describes those in prose around the generated block. So is HAM's
per-band power table (Settings › Bands & power), which is a grid of numbers
rather than one field per setting.

Needs PyQt6 (it opens the dialog), and never touches the operator's own
config: OHS_NB_CONF, OHS_NB_DATA and OHS_NB_UI_CONF (OHS_RADIO_* for Radio) point at a
throw-away folder. The radio is created but never started, so no device is
opened.
"""
from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GUIDES = {"nb": ROOT / "docs" / "USERGUIDE.md", "ham": ROOT / "docs" / "ham" / "USERGUIDE.md"}
GUIDE = GUIDES["nb"]
BEGIN = "<!-- settings-ref:begin (generated by tools/settings-ref.py; edit there, not here) -->"
END = "<!-- settings-ref:end -->"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _nb(tmp: str):
    """(state module, settings dialog, shutdown) for QO-100 NB."""
    os.environ["OHS_NB_CONF"] = str(Path(tmp) / "config.json")
    os.environ["OHS_NB_DATA"] = str(Path(tmp) / "data")
    os.environ["OHS_NB_UI_CONF"] = str(Path(tmp) / "ui.json")
    from ohsnb import state
    from ohsnb.radio import Radio
    from ohsnb.ui import make_app, shutdown
    from ohsnb.ui import settings as S
    from ohsnb.ui.face import Qo100Face
    from ohscore.ui.prefs import Prefs

    app = make_app(["settings-ref"])
    cfg = state.defaults(("setting", "control"))
    cfg.update(audioBackend="null")
    radio = Radio(cfg, persist=False, data_dir=Path(tmp) / "data")

    class Bridge:                      # all the dialog asks of the real one
        def __init__(self, r):
            self.radio, self.st, self.face = r, r.state(), Qo100Face()

    return app, state, S.SettingsDialog(Bridge(radio), Prefs(Path(tmp) / "ui.json")), shutdown


def _ham(tmp: str):
    """(state module, settings dialog, shutdown) for OpenHamShack Radio. Its face
    reads the bridge's state (the band under the dial), so it is handed the
    bridge."""
    os.environ["OHS_RADIO_CONF"] = str(Path(tmp) / "config.json")
    os.environ["OHS_RADIO_DATA"] = str(Path(tmp) / "data")
    os.environ["OHS_RADIO_UI_CONF"] = str(Path(tmp) / "ui.json")
    from ohsradio import state
    from ohsradio.radio import Radio
    from ohsradio.ui import make_app, shutdown
    from ohsradio.ui import settings as S
    from ohsradio.ui.face import HamFace
    from ohscore.ui.prefs import Prefs

    app = make_app(["settings-ref"])
    cfg = state.defaults(("setting", "control"))
    cfg.update(audioBackend="null")
    radio = Radio(cfg, persist=False, data_dir=Path(tmp) / "data")

    class Bridge:
        def __init__(self, r):
            self.radio, self.st, self.face = r, r.state(), HamFace(self)

    return app, state, S.SettingsDialog(Bridge(radio), Prefs(Path(tmp) / "ui.json")), shutdown


def generate(app: str = "nb") -> str:
    tmp = tempfile.mkdtemp(prefix=f"ohs{app}-settings-ref-")
    os.environ["QT_QPA_PLATFORM"] = "offscreen"
    sys.path.insert(0, str(ROOT))
    from PyQt6.QtWidgets import QComboBox, QLabel

    qapp, state, d, shutdown = (_ham if app == "ham" else _nb)(tmp)
    # Since the core split the labels live on the dialog class and the unit
    # formatter is a method (each app adds its own keys), so gather the
    # names the helpers below use into one place.
    from types import SimpleNamespace
    from ohscore.ui import settings as core
    S = SimpleNamespace(Field=core.Field, LABELS=d.LABELS, CHOICE_LABELS=d.CHOICE_LABELS,
                        _unit_fmt=d.unit_fmt, PAGES=d.PAGES, MHZ=d.MHZ_FIELDS, TYPED=d.TYPED_FIELDS)
    out = []
    for i, (_icon, page, *_rest) in enumerate(S.PAGES):
        fields = [f for f in d.stack.widget(i).findChildren(S.Field) if f.key in state.SPEC]
        combos = [w for w in d.stack.widget(i).findChildren(QComboBox) if w.property("settingKey") in state.SPEC]
        if not fields and not combos:
            continue
        out.append(f"#### {page}\n")
        out.append("| Setting | Range or choices | Default | What it does |")
        out.append("| --- | --- | --- | --- |")
        for f in fields:
            spec = state.SPEC[f.key]
            label = S.LABELS.get(f.key, f.key)
            helps = [w.text() for w in f.findChildren(QLabel) if w.objectName() == "Faint" and w.text()]
            what = " ".join(helps)
            if spec["restart"]:
                what += " *Restarts the radio when saved.*"
            out.append(f"| {_cell(label)} | {_cell(_range(S, f.key, spec))} | "
                       f"{_cell(_value(S, f.key, spec, spec['default']))} | {_cell(what.strip() or '-')} |")
        # Choices of a converter from the list (Settings › Converters) are
        # combo boxes rather than Fields, marked with the key they set.
        for cb in combos:
            key = cb.property("settingKey")
            spec = state.SPEC[key]
            what = spec["help"] + (" *Restarts the radio when saved.*" if spec["restart"] else "")
            default = spec["default"] or cb.property("settingNone") or "(none)"
            out.append(f"| {_cell(S.LABELS.get(key, key))} | a converter from the list | {_cell(default)} | "
                       f"{_cell(what)} |")
        out.append("")
    d.tester.close()
    d.deleteLater()
    shutdown()
    del qapp
    return "\n".join(out).rstrip() + "\n"


def _value(S, key, spec, v) -> str:
    t = spec["type"]
    if v is None:
        return "none (required)"
    if t == "bool":
        return "On" if v else "Off"
    if t == "enum":
        return S.CHOICE_LABELS.get(key, {}).get(v, str(v))
    if key in S.TYPED:
        return S.TYPED[key][0](v)
    if key in S.MHZ:
        return f"{v / 1e6:g} MHz"
    if t == "str":
        return f"`{v}`" if v else "(empty)"
    if spec["min"] is not None:
        return S._unit_fmt(key)(v)
    return str(v)


def _range(S, key, spec) -> str:
    t = spec["type"]
    if t == "enum":
        names = S.CHOICE_LABELS.get(key, {})
        return " / ".join(names.get(c, str(c)) for c in spec["choices"])
    if t == "bool":
        return "On / Off"
    if key in S.MHZ:
        return f"{spec['min'] / 1e6:g} – {spec['max'] / 1e6:g} MHz"
    if key in S.TYPED and spec["min"] is not None:
        fmt = S.TYPED[key][0]
        return f"{fmt(spec['min'])} – {fmt(spec['max'])}"
    if t in ("int", "float") and spec["min"] is not None:
        fmt = S._unit_fmt(key)
        return f"{fmt(spec['min'])} – {fmt(spec['max'])}"
    return "text"


def splice(guide: str, block: str, path: Path = GUIDE) -> str:
    a, b = guide.find(BEGIN), guide.find(END)
    if a < 0 or b < a:
        raise SystemExit(f"{path} has no {BEGIN!r} … {END!r} markers to write between")
    return guide[:a + len(BEGIN)] + "\n\n" + block + "\n" + guide[b:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--app", choices=sorted(GUIDES), default="nb", help="which program's Settings (default nb)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="replace the block in the app's guide")
    g.add_argument("--check", action="store_true", help="exit 1 if the guide's block is out of date")
    a = ap.parse_args()
    path = GUIDES[a.app]
    rel = path.relative_to(ROOT)
    block = generate(a.app)
    if not (a.write or a.check):
        sys.stdout.write(block)
        return 0
    guide = path.read_text(encoding="utf-8")
    new = splice(guide, block, path)
    if a.check:
        if new != guide:
            flag = "" if a.app == "nb" else f" --app {a.app}"
            print(f"{rel}: the settings reference is out of date; run tools/settings-ref.py{flag} --write",
                  file=sys.stderr)
            return 1
        return 0
    if new != guide:
        path.write_text(new, encoding="utf-8")
        print(f"updated {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
